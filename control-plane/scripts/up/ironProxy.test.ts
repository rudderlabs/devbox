import { describe, expect, it } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { parse } from "yaml";
import { parseConfig } from "./config";
import {
  DEFAULT_DNS_RESOLVER,
  DNS_RESOLVER,
  llmHost,
  llmPath,
  renderIronProxyConfig,
  TEMPLATE_PATH,
} from "./ironProxy";

const template = readFileSync(TEMPLATE_PATH, "utf8");

const cfg = parseConfig({
  repos: [{ url: "https://github.com/a/x.git" }, { url: "https://github.com/b/y.git" }],
  llm: { baseUrl: "https://openrouter.ai/api/v1", model: "m" },
});

describe("renderIronProxyConfig", () => {
  it("renders the whole config from the template", () => {
    const text = renderIronProxyConfig(template, cfg, "9.9.9.9:53");
    expect(text.startsWith("# Generated by `bun run up`")).toBe(true);
    expect(parse(text)).toEqual({
      dns: { listen: ":53", proxy_ip: "172.30.0.53", upstream_resolver: "9.9.9.9:53" },
      proxy: { http_listen: ":80", https_listen: ":443", max_request_body_bytes: 10485760 },
      tls: {
        ca_cert: "/certs/ca.crt",
        ca_key: "/certs/ca.key",
        cert_cache_size: 500,
        leaf_cert_expiry_hours: 24,
      },
      transforms: [
        {
          name: "allowlist",
          config: {
            rules: [
              { host: "codeload.github.com", methods: ["GET", "HEAD"], paths: ["/*"] },
              { host: "github.com", methods: ["GET", "HEAD"], paths: ["/*"] },
              { host: "github.com", methods: ["POST"], paths: ["/*/*/git-upload-pack"] },
              { host: "github.com", paths: ["/a/x/*", "/a/x.git/*"] },
              { host: "api.github.com", paths: ["/repos/a/x/*"] },
              { host: "raw.githubusercontent.com", paths: ["/a/x/*"] },
              { host: "github.com", paths: ["/b/y/*", "/b/y.git/*"] },
              { host: "api.github.com", paths: ["/repos/b/y/*"] },
              { host: "raw.githubusercontent.com", paths: ["/b/y/*"] },
              { host: "api.github.com", methods: ["GET", "HEAD"], paths: ["/users/*"] },
              {
                host: "*.blob.core.windows.net",
                methods: ["GET", "HEAD"],
                paths: ["/actions-results/*"],
              },
              { host: "openrouter.ai", methods: ["POST"], paths: ["/api/v1/responses"] },
            ],
          },
        },
        {
          name: "secrets",
          config: {
            secrets: [
              {
                source: { type: "env", var: "GITHUB_TOKEN" },
                proxy_value: "proxy-github-dummy-token",
                match_headers: ["Authorization"],
                rules: [
                  { host: "github.com" },
                  { host: "api.github.com" },
                  { host: "raw.githubusercontent.com" },
                ],
              },
              {
                source: { type: "env", var: "LLM_API_KEY" },
                proxy_value: "proxy-llm-dummy-token",
                match_headers: ["Authorization", "api-key", "x-api-key"],
                rules: [{ host: "openrouter.ai" }],
              },
            ],
          },
        },
      ],
      log: { level: "info" },
    });
  });

  const rulesFor = (github: { trustedOrgs: string[]; trustedUsers: string[] }) =>
    parse(renderIronProxyConfig(template, { ...cfg, github }, "9.9.9.9:53")).transforms[0].config
      .rules;

  it("adds a GET/HEAD members rule per trusted org, and the user and CI-log rules", () => {
    const rules = rulesFor({ trustedOrgs: ["example-org", "other-org"], trustedUsers: ["alice"] });
    expect(rules).toContainEqual({
      host: "api.github.com",
      methods: ["GET", "HEAD"],
      paths: ["/orgs/example-org/members", "/orgs/other-org/members"],
    });
    expect(rules).toContainEqual({
      host: "api.github.com",
      methods: ["GET", "HEAD"],
      paths: ["/users/*"],
    });
    expect(rules).toContainEqual({
      host: "*.blob.core.windows.net",
      methods: ["GET", "HEAD"],
      paths: ["/actions-results/*"],
    });
  });

  it("has no org rule without trusted orgs", () => {
    const rules = rulesFor({ trustedOrgs: [], trustedUsers: ["alice"] });
    expect(JSON.stringify(rules)).not.toContain("/orgs/");
  });

  it("rejects an org name that would widen the rule", () => {
    for (const org of ["a/b", "a*", "*", "../x", ""]) {
      expect(() => rulesFor({ trustedOrgs: [org], trustedUsers: [] })).toThrow(/trusted org/);
    }
  });

  it("reads the GitHub token from the file with githubTokenSource: file", () => {
    const secrets = (opts?: { githubTokenSource: "env" | "file" }) =>
      parse(renderIronProxyConfig(template, cfg, "9.9.9.9:53", opts)).transforms[1].config.secrets;
    expect(secrets({ githubTokenSource: "file" })[0].source).toEqual({
      type: "file",
      path: "/var/run/devbox/github/token",
      ttl: "60s",
    });
    expect(secrets({ githubTokenSource: "env" })[0].source).toEqual({
      type: "env",
      var: "GITHUB_TOKEN",
    });
    expect(secrets()[0].source).toEqual({ type: "env", var: "GITHUB_TOKEN" });
  });

  it("reads the token from another file in the token directory when given one", () => {
    const doc = parse(
      renderIronProxyConfig(template, cfg, "9.9.9.9:53", {
        githubTokenSource: "file",
        githubTokenFile: "/var/run/devbox/github/app-token",
      }),
    );
    expect(doc.transforms[1].config.secrets[0].source).toEqual({
      type: "file",
      path: "/var/run/devbox/github/app-token",
      ttl: "60s",
    });
  });

  it("has no RudderStack or GitHub App paths", () => {
    const text = renderIronProxyConfig(template, cfg, "9.9.9.9:53");
    for (const banned of ["rudderlabs", "installation", "app/installations", "AZURE"]) {
      expect(text).not.toContain(banned);
    }
  });

  it("allows only POST to the Messages API for anthropic", () => {
    const anthropic = parseConfig({
      ...cfgRaw(),
      llm: { provider: "anthropic", baseUrl: "https://api.anthropic.com", model: "m" },
    });
    const doc = parse(renderIronProxyConfig(template, anthropic, "9.9.9.9:53"));
    expect(doc.transforms[0].config.rules.at(-1)).toEqual({
      host: "api.anthropic.com",
      methods: ["POST"],
      paths: ["/v1/messages"],
    });
    expect(doc.transforms[1].config.secrets[1].rules).toEqual([{ host: "api.anthropic.com" }]);
  });
});

it("exports the default resolver and its shape", () => {
  expect(DEFAULT_DNS_RESOLVER).toBe("1.1.1.1:53");
  expect(DNS_RESOLVER.test("10.0.0.2:53")).toBe(true);
  expect(DNS_RESOLVER.test("[fd00::1]:53")).toBe(true);
  expect(DNS_RESOLVER.test("1.1.1.1")).toBe(false);
});

function cfgRaw() {
  return { repos: [{ url: "https://github.com/a/x.git" }] };
}

describe("llmHost and llmPath", () => {
  it("split the base URL", () => {
    expect(llmHost("https://api.openai.com/v1")).toBe("api.openai.com");
    expect(llmHost("http://ollama.lan:11434/v1")).toBe("ollama.lan");
  });

  it("name the one endpoint each provider calls", () => {
    const openai = (baseUrl: string) => llmPath({ provider: "openai", baseUrl });
    const anthropic = (baseUrl: string) => llmPath({ provider: "anthropic", baseUrl });
    expect(openai("https://api.openai.com/v1")).toBe("/v1/responses");
    expect(openai("https://x.openai.azure.com/openai/v1/")).toBe("/openai/v1/responses");
    expect(anthropic("https://api.anthropic.com")).toBe("/v1/messages");
    expect(anthropic("https://gw.example/anthropic")).toBe("/anthropic/v1/messages");
  });
});

it("TEMPLATE_PATH points into infra/local", () => {
  expect(TEMPLATE_PATH.endsWith(join("infra", "local", "iron-proxy.template.yaml"))).toBe(true);
});
